"""
Write docs/REVIEW_CHECKLIST.md: every fact sheet split into sentences, as checkboxes,
with its sources next to it, most-sighted species first. Reviewers tick each sentence
once they've found it in a source, then fill in the sheet's "reviewed_by:" line.

Re-run after editing fact sheets (it overwrites the checklist, so finish ticking first):
Usage (from backend/):  python scripts/make_review_checklist.py
"""

import re
from pathlib import Path

import _setup  # noqa: F401  (adds backend/ to the import path)

from app import config, data
from app.rag.chunker import GENERAL, _split_front_matter, chunk_file

OUT = config.BACKEND_DIR.parent / "docs" / "REVIEW_CHECKLIST.md"
DEMO_SPECIES = {"Cygnus olor"}  # used in the demo script (docs/DEMO.md), so check these first
GROUP_SIZE = 10


def sentences(text):
    """Split a paragraph into sentences (good enough for review; a few may split oddly)."""
    text = " ".join(text.split())
    return [s for s in re.split(r"(?<=[.!?])\s+(?=[A-Z\"“(])", text) if s]


def sheet_block(rank, path, sightings, common_names):
    header, _ = _split_front_matter(path.read_text())
    chunks = chunk_file(path)
    name = chunks[0].scientific_name if chunks else header.get("scientific_name", path.stem)
    title = "General reporting text (shown for every species)" if name == GENERAL else f"{common_names.get(name, '')} (*{name}*)"
    done = "✅ reviewed" if header.get("reviewed_by") else "draft"
    demo = " · **in the demo**" if name in DEMO_SPECIES else ""
    lines = [
        f"### {rank}. {title} · {sightings:,} sightings{demo} · {done}",
        "",
        f"File: [`backend/knowledge/{path.name}`](../backend/knowledge/{path.name})",
        "",
        "Sources:",
    ]
    for source in header.get("sources") or []:
        lines.append(f"- [{source.get('title', source.get('url'))}]({source.get('url')})")
    if header.get("touch_safe") is not None:
        lines += ["", f"- [ ] `touch_safe: {str(header['touch_safe']).lower()}` is stated explicitly by a source"]
    for chunk in chunks:
        lines += ["", f"**{chunk.section}**", ""]
        lines += [f"- [ ] {s}" for s in sentences(chunk.text)]
    lines += ["", f"- [ ] All sentences checked → put your name on `reviewed_by:` in `{path.name}`", ""]
    return lines


def main():
    species = data.species_list()
    counts = {s["scientific_name"]: s["sightings"] for s in species}
    common_names = {s["scientific_name"]: s["common_name"] for s in species}
    sheets = []
    for path in sorted(Path(config.KNOWLEDGE_DIR).glob("*.md")):
        if path.name.startswith("_"):
            continue
        chunks = chunk_file(path)
        name = chunks[0].scientific_name if chunks else None
        # The general reporting file is shown for every species, so it goes first.
        sightings = sum(counts.values()) if name == GENERAL else counts.get(name, 0)
        priority = (0 if name == GENERAL else 1 if name in DEMO_SPECIES else 2, -sightings)
        sheets.append((priority, path, sightings))
    sheets.sort(key=lambda item: item[0])

    lines = [
        "# Fact-sheet review checklist",
        "",
        "Generated by `backend/scripts/make_review_checklist.py`. Re-running it overwrites this file.",
        "",
        "**What to check, sentence by sentence:** the fact is in one of the listed sources (in our own words is fine), "
        "numbers, dates and places match exactly, and nothing is added (no \"annually\", no extra advice). "
        "If a sentence isn't in any source, **delete it or fix it in the fact sheet**; don't tick it. "
        "\"In NYC parks like Kissena…\" sentences come from the NYC Parks Rules source.",
        "",
        "**When a sheet is done:** put your name on its `reviewed_by:` line, update the \"Written by\" column "
        "in `docs/DATA_SOURCES.md`, then tell Backend to run `python scripts/load_chunks.py` and "
        "`python scripts/build_insights.py` if you changed any text (a name alone only needs a backend restart).",
        "",
        f"Order: the general reporting text, then the demo species, then by number of sightings. "
        f"Split it up in groups of {GROUP_SIZE}.",
        "",
    ]
    for i, (_, path, sightings) in enumerate(sheets):
        if i % GROUP_SIZE == 0:
            lines += [f"## Group {i // GROUP_SIZE + 1} (sheets {i + 1}–{min(i + GROUP_SIZE, len(sheets))}) · reviewer: ______", ""]
        lines += sheet_block(i + 1, path, sightings, common_names)

    OUT.write_text("\n".join(lines))
    print(f"Wrote {OUT.relative_to(config.BACKEND_DIR.parent)} ({len(sheets)} sheets)")


if __name__ == "__main__":
    main()
